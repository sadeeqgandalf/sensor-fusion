function [omega, comp] = simulateGyro(T, fs, N, B, K, rngSeed)
%SF.IMU.SIMULATEGYRO Static single-axis gyro output with IEEE-952 noise terms.
%
%   [omega, comp] = sf.imu.simulateGyro(T, fs, N, B, K, seed)
%
%   T   record length [s]           fs  sample rate [Hz]
%   N   angle random walk           [rad/s/sqrt(Hz)]   Allan slope -1/2
%   B   bias instability            [rad/s]            Allan flat region
%   K   rate random walk            [rad/s^2/sqrt(Hz)] Allan slope +1/2
%
%   Noise models (two-sided PSD convention, as in IEEE Std 952):
%     white    S(f) = N^2                -> per-sample std  N*sqrt(fs)
%     flicker  S(f) = (B^2 / 2pi) / |f|  -> generated by FFT spectral shaping
%     RRW      S(f) = (K/2pi)^2 / f^2    -> integrated white noise
%
%   comp returns each component separately so the Allan plot can show
%   which term dominates at which averaging time.

if nargin >= 6, rng(rngSeed); end

n  = round(T * fs);
dt = 1 / fs;

% --- Angle random walk: white rate noise ---------------------------------
comp.white = N * sqrt(fs) * randn(n, 1);

% --- Bias instability: 1/f (flicker) noise by spectral shaping ------------
% Unit-variance white noise has two-sided PSD 1/fs. Multiplying its
% spectrum by H(f) = sqrt(S(f) * fs) gives a sequence with PSD S(f).
nfft = 2^nextpow2(n);
f    = (0:nfft-1).' * fs / nfft;
f(f > fs/2) = f(f > fs/2) - fs;          % signed frequency axis
H    = sqrt((B^2 / (2*pi)) ./ abs(f) * fs);
H(1) = 0;                                % no DC: the constant bias is calibrated out
X    = fft(randn(nfft, 1)) .* H;
flk  = real(ifft(X));
comp.flicker = flk(1:n);

% --- Rate random walk: integrated white noise -----------------------------
comp.rrw = cumsum(K * sqrt(dt) * randn(n, 1));

omega = comp.white + comp.flicker + comp.rrw;
end
